import {afterEach,beforeEach,expect,it,vi} from 'vitest';
import {cleanup,render,screen,within} from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import {QueryClient,QueryClientProvider} from '@tanstack/react-query';
import {MemoryRouter,Routes,Route} from 'react-router-dom';
import InvoiceEmissionPage from '@/modules/invoices/pages/InvoiceEmissionPage';
import {useAuthStore} from '@/stores/authStore';
vi.mock('@/lib/axios',()=>({apiClient:{get:vi.fn(async(url:string)=>({data:url.includes('/invoices/products')?{balances:[{sku:'CEM-001',description:'Cemento prueba',sunatUnitCode:'NIU',taxAffectation:'10',currentStock:20,salePrice:118,vendible:true,activo:true}]}:url.includes('/invoices/config')?{series:[{document_type:'01',series:'F001',is_active:true}],perfil_comercial:'MAYORISTA'}:[]}))}}));
vi.mock('@/modules/invoices/components/RetencionMaestro',()=>({RetencionMaestro:()=>null}));
const clients:QueryClient[]=[];
beforeEach(()=>useAuthStore.setState({user:{id:'local',email:'local@example.invalid',role:'ADMIN'}}));
afterEach(()=>{cleanup();clients.splice(0).forEach(c=>c.clear());});
it('Liquidación de la ruta real separa IGV referencial del cobrado y del total',async()=>{
 const q=new QueryClient({defaultOptions:{queries:{retry:false,gcTime:0}}});clients.push(q);
 render(<QueryClientProvider client={q}><MemoryRouter initialEntries={['/invoices/emision?tipo=01']}><Routes><Route path="/invoices/emision" element={<InvoiceEmissionPage/>}/></Routes></MemoryRouter></QueryClientProvider>);
 const user=userEvent.setup();const search=await screen.findByRole('combobox',{name:'Buscar producto'});
 const card=screen.getByText('Liquidación').closest('[data-slot="card"]') as HTMLElement;
 expect(within(card).queryByText(/IGV referencial/)).toBeNull();
 await user.type(search,'CEM');await user.click(screen.getByRole('button',{name:/CEM-001 · Cemento prueba/}));
 await user.click(screen.getByLabelText('Gratuita de la línea 1'));
 await user.selectOptions(screen.getByLabelText('Motivo de gratuidad de la línea 1'),'11');
 expect(within(card).getByText('Op. gratuita (referencial)').parentElement?.textContent).toContain('100.00');
 expect(within(card).getByText('IGV referencial (no se cobra)').parentElement?.textContent).toContain('18.00');
 expect(within(card).getByText('IGV (18 %)').parentElement?.textContent).toContain('0.00');
 expect(within(card).getByText('Importe total').parentElement?.textContent).toContain('0.00');
 await user.selectOptions(screen.getByLabelText('Motivo de gratuidad de la línea 1'),'31');
 expect(within(card).queryByText(/IGV referencial/)).toBeNull();
 expect(within(card).getByText('Importe total').parentElement?.textContent).toContain('0.00');
});
